#!/usr/bin/env python3
"""Copy the samples (../samples, listed in samples.json) into ui/samples/ and write ui/samples.js.

Per sample: the input file and, when present, the agent's saved answer (output/<stem>.result.json, written by
samples/run_sample.py) so the UI can show an example estimate without running the agent.
"""
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT.parent / "samples"
DEST = ROOT / "ui" / "samples"


def main() -> None:
    if DEST.exists():
        shutil.rmtree(DEST)
    DEST.mkdir(parents=True)
    samples = []
    for meta in json.loads((SRC / "samples.json").read_text(encoding="utf-8")):
        src = SRC / meta["file"]
        shutil.copyfile(src, DEST / src.name)
        item = {**meta, "path": f"samples/{src.name}", "size": src.stat().st_size, "example": None}
        result = SRC / "output" / f"{src.stem}.result.json"
        if result.exists():
            shutil.copyfile(result, DEST / result.name)
            item["example"] = f"samples/{result.name}"
        samples.append(item)
    (ROOT / "ui" / "samples.js").write_text(
        "// Generated by scripts/sync_samples.py from ../samples. Do not edit.\n"
        f"window.COST_SAMPLES = {json.dumps(samples, indent=2, ensure_ascii=False)};\n",
        encoding="utf-8",
    )
    print(f"{len(samples)} sample(s): {', '.join(s['file'] for s in samples)}")


if __name__ == "__main__":
    main()
