#!/usr/bin/env python3
"""Copy the sample engagements into ui/samples/ and write ui/samples.js for the "Use sample" button.

Sources, in order: the SOW agent's samples (../../sow-generator-agent/samples) and this project's own (../samples).
A sample is a *pipeline input*, so the architecture and cost blocks are stripped from its upstream.json: this pipeline
produces them (the architect designs from the SOW, the cost agent prices the design), and feeding them in would let a
stale figure into a run that is meant to compute its own. The example SOW is kept, so "Use with example SOW" can skip
the drafting stage for a quick demo.
"""
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [ROOT.parents[1] / "sow-generator-agent" / "samples", ROOT.parent / "samples"]
DEST = ROOT / "ui" / "samples"
PRODUCED_BY_THE_PIPELINE = ("architecture", "cost")


def intake_only(upstream: dict) -> dict:
    """The upstream handoff without the blocks the pipeline computes itself."""
    cleaned = {k: v for k, v in upstream.items() if k not in PRODUCED_BY_THE_PIPELINE}
    meta = dict(cleaned.get("meta") or {})
    if isinstance(meta.get("source_agents"), list):
        meta["source_agents"] = [a for a in meta["source_agents"] if a not in ("architecture", "cost-estimate", "cost")]
    cleaned["meta"] = meta
    return cleaned


def main() -> None:
    if DEST.exists():
        shutil.rmtree(DEST)
    samples = []
    for source in SOURCES:
        if not source.is_dir():
            continue
        for folder in sorted(p for p in source.iterdir() if p.is_dir() and (p / "sample.json").exists()):
            meta = json.loads((folder / "sample.json").read_text(encoding="utf-8"))
            dest = DEST / folder.name
            dest.mkdir(parents=True)
            base = f"samples/{folder.name}"
            item = {"id": folder.name,
                    **{k: meta.get(k) for k in ("title", "summary", "customer_name", "opportunity_id", "template_id")},
                    "details": None, "upstream": None, "example_md": None}
            if (folder / "project-details.txt").exists():
                shutil.copyfile(folder / "project-details.txt", dest / "project-details.txt")
                item["details"] = f"{base}/project-details.txt"
            if (folder / "upstream.json").exists():
                upstream = intake_only(json.loads((folder / "upstream.json").read_text(encoding="utf-8")))
                (dest / "upstream.json").write_text(json.dumps(upstream, indent=2, ensure_ascii=False) + "\n",
                                                    encoding="utf-8")
                item["upstream"] = f"{base}/upstream.json"
            sow = folder / "output" / "sow.md"
            if sow.exists():
                shutil.copyfile(sow, dest / "example-sow.md")
                item["example_md"] = f"{base}/example-sow.md"
            samples.append(item)
    (ROOT / "ui" / "samples.js").write_text(
        "// Generated by scripts/sync_samples.py. Do not edit.\n"
        f"window.PIPELINE_SAMPLES = {json.dumps(samples, indent=2, ensure_ascii=False)};\n", encoding="utf-8")
    print(f"{len(samples)} sample(s): {', '.join(s['id'] for s in samples)}")


if __name__ == "__main__":
    main()
