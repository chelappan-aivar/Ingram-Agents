#!/usr/bin/env python3
"""Write ui/templates.js: the template catalogue the form's dropdown shows.

Read from the SOW agent's own templates (../../sow-generator-agent/resources/templates) so the UI cannot offer a template
the SOW agent does not have. Ids and labels follow the runtime (repositories/template_repository.py).
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT.parents[1] / "sow-generator-agent" / "resources" / "templates"
CATEGORY_LABELS = {"aiml": "AI/ML", "devops": "DevOps", "cva": "CVA"}
STEM = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]*$")


def titleize(stem: str) -> str:
    return " ".join(p[:1].upper() + p[1:] for p in re.split(r"[-_]", stem))


def catalogue() -> list[dict]:
    templates = []
    for category in sorted(p for p in SRC.iterdir() if p.is_dir() and p.name in CATEGORY_LABELS):
        for md in sorted(category.glob("*.md")):
            stem = md.name.removesuffix(".md")
            if STEM.match(stem):
                templates.append({"id": f"{category.name}/{stem}", "category": category.name,
                                  "label": f"{CATEGORY_LABELS[category.name]} \u2014 {titleize(stem)}"})
    return templates


def main() -> None:
    templates = catalogue()
    (ROOT / "ui" / "templates.js").write_text(
        "// Generated by scripts/sync_templates.py from the SOW agent's templates. Do not edit.\n"
        f"window.PIPELINE_TEMPLATES = {json.dumps(templates, indent=2, ensure_ascii=False)};\n", encoding="utf-8")
    print(f"{len(templates)} template(s): {', '.join(t['id'] for t in templates)}")


if __name__ == "__main__":
    main()
