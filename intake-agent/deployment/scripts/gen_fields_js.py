"""Write ui/fields.js from agent/intake/fields.py so the UI always shows the agent's real field catalogue.

    python3 scripts/gen_fields_js.py      (run by deploy.sh)
"""

import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("fields", ROOT / "agent" / "intake" / "fields.py")
fields = importlib.util.module_from_spec(spec)
spec.loader.exec_module(fields)

catalogue = [{"group": group, "fields": [{"id": fid, "label": label, "key": key} for fid, label, key in items]}
             for group, items in fields.FIELD_GROUPS]
(ROOT / "ui" / "fields.js").write_text(
    "// Generated by scripts/gen_fields_js.py from agent/intake/fields.py. Do not edit by hand.\n"
    f"window.INTAKE_FIELDS = {json.dumps(catalogue, indent=2)};\n")
print(f"ui/fields.js: {sum(len(g['fields']) for g in catalogue)} fields in {len(catalogue)} groups")
