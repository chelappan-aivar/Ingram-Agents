#!/usr/bin/env bash
# Deploy the SOW Generator web UI against the existing SowGenAgent backend:
#   backend API URL -> Amplify app stack -> CORS -> ui/config.js + templates -> CSP -> Amplify Hosting
#   ./scripts/deploy.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

# ---------------------------------------------------------------- config
[[ -f config.env ]] || { echo "config.env not found (cp config.env.example config.env)"; exit 1; }
set -a; source config.env; set +a
for var in AWS_REGION STACK_NAME SOW_API_STACK UI_ORIGIN; do
  value="${!var:-}"
  if [[ -z "$value" || "$value" == "REPLACE_ME" || "$value" == \<* ]]; then
    echo "config.env: $var is not set"; exit 1
  fi
done
[[ -n "${AWS_PROFILE:-}" ]] || unset AWS_PROFILE
export AWS_REGION AWS_DEFAULT_REGION="$AWS_REGION"

for tool in aws zip curl python3; do
  command -v "$tool" >/dev/null || { echo "$tool is required"; exit 1; }
done
python3 -c "import boto3" 2>/dev/null || { echo "python3 needs boto3 (pip install boto3)"; exit 1; }
ACCOUNT_ID="$(aws sts get-caller-identity --query Account --output text)"
echo "Deploying $STACK_NAME to account $ACCOUNT_ID ($AWS_REGION), backend stack $SOW_API_STACK"

output() {   # output <stack> <key>
  aws cloudformation describe-stacks --stack-name "$1" \
    --query "Stacks[0].Outputs[?OutputKey=='$2'].OutputValue" --output text
}

# ---------------------------------------------------------------- 1. backend (already deployed)
API_URL="$(output "$SOW_API_STACK" ApiUrl)"          # https://<id>.execute-api.<region>.amazonaws.com/<stage>/
[[ "$API_URL" == https://* ]] || { echo "stack $SOW_API_STACK has no ApiUrl output"; exit 1; }
SOW_API="${API_URL%/}/api/v1/sow"
API_ORIGIN="$(echo "$API_URL" | sed -E 's#^(https://[^/]+).*#\1#')"
echo "Backend API: $SOW_API"

# ---------------------------------------------------------------- 2. Amplify app (CloudFormation)
aws cloudformation deploy \
  --template-file template.yaml \
  --stack-name "$STACK_NAME" \
  --tags Project=ingram-sow \
  --no-fail-on-empty-changeset
UI_URL="$(output "$STACK_NAME" UiUrl)"
UI_APP_ID="$(output "$STACK_NAME" UiAppId)"

# ---------------------------------------------------------------- 3. CORS on the backend: Amplify URL, UI_ORIGIN + CORS_EXTRA_ORIGINS
ORIGINS="$UI_URL,$UI_ORIGIN${CORS_EXTRA_ORIGINS:+,$CORS_EXTRA_ORIGINS}"
ORIGINS="$(echo "$ORIGINS" | tr ',' '\n' | sed -E 's#/+$##' | grep -v '^$' | awk '!seen[$0]++' | paste -sd, -)"
if [[ "${UPDATE_API_CORS:-true}" == "true" ]]; then
  python3 scripts/update_cors.py --stack "$SOW_API_STACK" --region "$AWS_REGION" --origins "$ORIGINS"
else
  echo "UPDATE_API_CORS=false: allow these origins on the backend yourself: $ORIGINS"
fi

# ---------------------------------------------------------------- 4. UI config + template catalogue
cat > ui/config.js <<EOF
// Generated by scripts/deploy.sh. Safe to commit: contains no secrets.
window.SOW_CONFIG = {
  apiUrl: "${SOW_API}",
};
EOF
python3 scripts/sync_templates.py
python3 scripts/sync_samples.py     # ../samples -> ui/samples + ui/samples.js (the "Samples" card)

# ---------------------------------------------------------------- 5. web UI -> Amplify Hosting (manual deployment)
UI_ZIP="$ROOT/build/ui.zip"
mkdir -p "$ROOT/build" && rm -f "$UI_ZIP"
# Pin the page's Content-Security-Policy to this exact API host.
# .docx downloads are navigations to a presigned S3 URL, not fetches, so connect-src needs only the API.
STAGE_UI="$ROOT/build/ui" && rm -rf "$STAGE_UI" && cp -R ui "$STAGE_UI"
sed -i.bak -E "s#connect-src 'self' [^;]*;#connect-src 'self' ${API_ORIGIN};#" "$STAGE_UI/index.html" && rm -f "$STAGE_UI/index.html.bak"
grep -q "connect-src 'self' ${API_ORIGIN};" "$STAGE_UI/index.html" || { echo "could not set CSP connect-src"; exit 1; }
(cd "$STAGE_UI" && zip -qr -X "$UI_ZIP" index.html styles.css app.js markdown.js draft.js config.js templates.js templates samples.js samples)
read -r JOB_ID UPLOAD_URL < <(aws amplify create-deployment --app-id "$UI_APP_ID" --branch-name main \
  --query "[jobId, zipUploadUrl]" --output text)
curl --fail --silent --show-error -X PUT -H "Content-Type: application/zip" --upload-file "$UI_ZIP" "$UPLOAD_URL"
aws amplify start-deployment --app-id "$UI_APP_ID" --branch-name main --job-id "$JOB_ID" >/dev/null
echo -n "Publishing UI (Amplify job $JOB_ID)"
STATUS=""
for _ in $(seq 1 60); do
  STATUS="$(aws amplify get-job --app-id "$UI_APP_ID" --branch-name main --job-id "$JOB_ID" \
    --query "job.summary.status" --output text)"
  case "$STATUS" in
    SUCCEED) echo " done"; break ;;
    FAILED|CANCELLED) echo " $STATUS"; exit 1 ;;
    *) echo -n "."; sleep 5 ;;
  esac
done
[[ "$STATUS" == "SUCCEED" ]] || { echo " timed out (status $STATUS)"; exit 1; }
rm -rf "$ROOT/build"

# ---------------------------------------------------------------- 6. summary
echo
echo "Done."
echo "  UI:   $UI_URL"
echo "  API:  $SOW_API"
echo "  CORS: $ORIGINS"
echo "Smoke test (0 model calls): curl -s -X POST $SOW_API/sessions -H 'Content-Type: application/json' -d '{}'"
echo "Local UI (optional): python3 -m http.server ${UI_ORIGIN##*:} --directory ui   then open $UI_ORIGIN"
