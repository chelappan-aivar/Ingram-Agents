#!/usr/bin/env python3
"""Copy the sample engagements (../samples/<id>/) into ui/samples/ and write ui/samples.js for the "Samples" card.

Per sample: sample.json (form values), project-details.txt, upstream.json, the transcript / image files and the
example output (output/sow.md and output/*.docx). run.json and check.json stay out of the UI.
"""
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT.parent / "samples"
DEST = ROOT / "ui" / "samples"
TRANSCRIPT_EXT = {".pdf", ".docx", ".txt", ".md", ".csv", ".xlsx"}
IMAGE_EXT = {".png", ".jpg", ".jpeg"}
FORM_FILES = {"sample.json", "project-details.txt", "upstream.json"}


def main() -> None:
    if DEST.exists():
        shutil.rmtree(DEST)
    samples = []
    for folder in sorted(p for p in SRC.iterdir() if p.is_dir() and (p / "sample.json").exists()):
        meta = json.loads((folder / "sample.json").read_text(encoding="utf-8"))
        dest = DEST / folder.name
        dest.mkdir(parents=True)
        base = f"samples/{folder.name}"
        files = []
        for f in sorted(p for p in folder.iterdir() if p.is_file() and p.name not in FORM_FILES):
            kind = "image" if f.suffix.lower() in IMAGE_EXT else "transcript" if f.suffix.lower() in TRANSCRIPT_EXT else None
            if kind:
                shutil.copyfile(f, dest / f.name)
                files.append({"name": f.name, "kind": kind, "size": f.stat().st_size, "path": f"{base}/{f.name}"})
        item = {"id": folder.name, **{k: meta.get(k) for k in ("title", "summary", "customer_name", "opportunity_id", "template_id")},
                "files": files, "details": None, "upstream": None, "example_md": None, "example_docx": None}
        for name, key in (("project-details.txt", "details"), ("upstream.json", "upstream")):
            if (folder / name).exists():
                shutil.copyfile(folder / name, dest / name)
                item[key] = f"{base}/{name}"
        out = folder / "output"
        if (out / "sow.md").exists():
            shutil.copyfile(out / "sow.md", dest / "example-sow.md")
            item["example_md"] = f"{base}/example-sow.md"
        docx = sorted(out.glob("*.docx")) if out.is_dir() else []
        if docx:
            shutil.copyfile(docx[0], dest / docx[0].name)
            item["example_docx"] = f"{base}/{docx[0].name}"
        samples.append(item)
    (ROOT / "ui" / "samples.js").write_text(
        "// Generated by scripts/sync_samples.py from ../samples. Do not edit.\n"
        f"window.SOW_SAMPLES = {json.dumps(samples, indent=2, ensure_ascii=False)};\n",
        encoding="utf-8",
    )
    print(f"{len(samples)} sample(s): {', '.join(s['id'] for s in samples)}")


if __name__ == "__main__":
    main()
