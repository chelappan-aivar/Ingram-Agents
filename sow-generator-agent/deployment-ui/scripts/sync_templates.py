#!/usr/bin/env python3
"""Copy the SOW templates (../resources/templates) into ui/templates/ and write ui/templates.js.

The live API has no template endpoints, so the UI ships the catalogue as static files. Ids and labels follow
the runtime (repositories/template_repository.py): id "<category>/<stem>", label "<Category> — <Title Stem>".
"""
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT.parent / "resources" / "templates"
DEST = ROOT / "ui" / "templates"
CATEGORY_LABELS = {"aiml": "AI/ML", "devops": "DevOps", "cva": "CVA"}
STEM = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]*$")


def titleize(stem: str) -> str:
    return " ".join(p[:1].upper() + p[1:] for p in re.split(r"[-_]", stem))


def main() -> None:
    if DEST.exists():
        shutil.rmtree(DEST)
    templates = []
    for category in sorted(p for p in SRC.iterdir() if p.is_dir() and p.name in CATEGORY_LABELS):
        for md in sorted(category.glob("*.md")):
            stem = md.name.removesuffix(".md")
            if not STEM.match(stem):
                continue
            (DEST / category.name).mkdir(parents=True, exist_ok=True)
            shutil.copyfile(md, DEST / category.name / md.name)
            templates.append({"id": f"{category.name}/{stem}", "category": category.name,
                              "label": f"{CATEGORY_LABELS[category.name]} \u2014 {titleize(stem)}",
                              "path": f"templates/{category.name}/{md.name}"})
    (ROOT / "ui" / "templates.js").write_text(
        "// Generated by scripts/sync_templates.py from ../resources/templates. Do not edit.\n"
        f"window.SOW_TEMPLATES = {json.dumps(templates, indent=2, ensure_ascii=False)};\n",
        encoding="utf-8",
    )
    print(f"{len(templates)} template(s): {', '.join(t['id'] for t in templates)}")


if __name__ == "__main__":
    main()
