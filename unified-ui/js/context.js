// Turns one agent's output into the next agent's input. Pure functions, no DOM.
import { trunc } from "./util.js";

const fv = (opp, id) => String((opp.fields || []).find((f) => f.field === id)?.value ?? "").trim();
const lines = (s) => s.split(/\n|;|•/).map((x) => x.trim()).filter(Boolean);

export function customerOf(opp) { return opp.customer_name || fv(opp, "customer_name") || "Unknown customer"; }

// The opportunity the downstream agents work on: a real opportunity with the most verified facts.
export function pickOpportunity(opps) {
  const real = opps.filter((o) => o.is_opportunity !== false && customerOf(o) !== "Unknown customer");
  return [...real].sort((a, b) => (b.verified_count || 0) - (a.verified_count || 0) || (b.field_count || 0) - (a.field_count || 0))[0] || null;
}

export function intakeMarkdown(opp) {
  const out = [`# Intake record: ${customerOf(opp)}`, "", opp.summary || ""];
  const groups = {};
  for (const f of opp.fields || []) if (String(f.value ?? "").trim()) (groups[f.group || "General"] ||= []).push(f);
  for (const [g, fs] of Object.entries(groups)) {
    out.push("", `## ${g}`);
    for (const f of fs) out.push(`- **${f.label || f.field}**: ${f.value}${f.verified ? "" : " (unverified)"}`);
  }
  if ((opp.gaps || []).length) out.push("", "## Open gaps", ...opp.gaps.map((g) => `- ${g.label || g.field}: ${g.question || g.why}`));
  if ((opp.conflicts || []).length) out.push("", "## Conflicts", ...opp.conflicts.map((c) => `- ${c.label || c.field}: ${c.detail}`));
  return out.join("\n");
}

export function discoveryMarkdown(report, narrative) {
  const out = ["# Discovery findings", ""];
  for (const p of narrative?.executive_summary || []) out.push(String(p), "");
  out.push("## Pain points", ...(report?.what_we_heard?.pain_points || []).map((p) => `- ${p.text}`));
  out.push("", "## Use cases", ...(report?.use_cases || []).map((u) => `- ${u.title}: ${u.problem || ""}`));
  out.push("", "## Hidden opportunities", ...(report?.top_hidden_opportunities || []).map((h) => `- ${h.title}: ${h.why_it_matters || ""}`));
  out.push("", "## Open questions", ...(report?.gaps_and_open_questions || []).map((g) => `- ${g.question}`));
  return out.join("\n");
}

// Live Assist call description (API cap 2000 chars): the intake summary, plus discovery findings on the second pass.
export function liveAssistDescription(opp, discovery) {
  const parts = [opp.summary || "", `Open gaps: ${(opp.gaps || []).map((g) => g.label || g.field).join(", ")}`];
  if (discovery?.report) {
    parts.push("Discovery pain points: " + (discovery.report.what_we_heard?.pain_points || []).map((p) => p.text).join("; "));
    parts.push("Discovery open questions: " + (discovery.report.gaps_and_open_questions || []).map((g) => g.question).join("; "));
  }
  return trunc(parts.filter(Boolean).join("\n"), 2000);
}

export function upstreamFor(opp, templateId, { discovery, la, arch, cost } = {}) {
  const oppId = String(opp.dynamics_id || opp.thread_key || `OPP-${Date.now()}`).replace(/[^\w.-]+/g, "-").slice(0, 100);
  const intake = { customer_name: customerOf(opp) };
  const set = (k, v) => { if (v && (!Array.isArray(v) || v.length)) intake[k] = v; };
  set("industry", fv(opp, "industry"));
  set("engagement_type", fv(opp, "opportunity_type"));
  set("problem_statement", fv(opp, "business_problem") || opp.summary || "");
  set("goals", lines(fv(opp, "desired_outcomes")));
  set("timeline", fv(opp, "timeline"));
  set("budget_range", fv(opp, "budget"));
  set("constraints", [fv(opp, "compliance"), fv(opp, "security_requirements"), fv(opp, "out_of_scope")].filter(Boolean));
  const up = { meta: { schema_version: "1.0", opportunity_id: oppId, template_id: templateId, source_agents: ["intake"] }, intake };
  if (discovery?.report) {
    const r = discovery.report;
    up.discovery = {
      source: "discovery",
      findings: [...(r.what_we_heard?.pain_points || []).map((p) => p.text), ...(r.top_hidden_opportunities || []).map((h) => `${h.title}: ${h.why_it_matters || ""}`)].filter(Boolean),
      requirements: (r.use_cases || []).map((u) => `${u.title}: ${u.problem || ""}`),
      notes: (discovery.narrative?.executive_summary || []).join("\n\n") || null,
    };
    up.meta.source_agents.push("discovery");
  }
  if (la?.questions?.length) {
    up.live_assist = { source: "live_assist", findings: la.questions.map((q) => q.question), requirements: [], notes: "Pre-call questions generated by Live Assist." };
    up.meta.source_agents.push("live_assist");
  }
  if (arch || cost) {
    const lines = Object.values(cost?.environments || {}).flatMap((e) => e.services || []);
    if (lines.length || arch?.adr) up.architecture = { services: lines.map((x) => ({ name: x.name || x.service || "Service", purpose: x.description || "" })) };
    if (cost) { up.cost = { currency: "USD", line_items: lines.map((x) => ({ service: x.name || x.service || "Service", notes: x.description || "" })), source_link: cost.calculatorUrl || null }; }
    up.meta.source_agents.push(...["architecture", "cost"].filter((k) => (k === "architecture" ? arch : cost)));
  }
  return up;
}

// Free text the SOW agent reads alongside `upstream`.
export function projectDetails(opp, discovery, arch) {
  return [intakeMarkdown(opp), discovery?.report ? discoveryMarkdown(discovery.report, discovery.narrative) : "",
    arch?.adr ? `# Architecture decisions\n\n${arch.adr.slice(0, 30000)}` : ""].filter(Boolean).join("\n\n");
}

// Plain-text workload description for the Cost agent (30 to 20,000 characters).
export function costRequirements(opp, arch) {
  return trunc(`AWS workload for ${customerOf(opp)}. ${opp.summary || ""}\n\n${arch?.adr || ""}`.trim(), 19500);
}

// Final-SOW guarantees. The model usually places the diagram and the calculator link, but the hub does not rely on that:
// if either is missing from the combined SOW it is added, so the document always carries both.
export function finalizeSow(md, { calcUrl = "", hasDiagram = false } = {}) {
  let out = md;
  if (hasDiagram && !/\]\(arch:\d+\)/.test(out)) {
    const img = "![Architecture Diagram](arch:1)";
    const head = out.match(/^#{1,3}[ \t]+.*architecture.*$/im);
    out = head ? out.replace(head[0], `${head[0]}\n\n${img}`) : `${out}\n\n## Solution Architecture\n\n${img}`;
  }
  if (calcUrl && !out.includes(calcUrl)) {
    out = /\[cost calculator link\]/i.test(out) ? out.replace(/\[cost calculator link\]/gi, calcUrl)
      : `${out}\n\n## AWS Cost Estimate\n\nAWS Pricing Calculator estimate: ${calcUrl}`;
  }
  return out;
}

// Table of contents rebuilt from the SOW's own headings (outside code fences), so it always matches the current text.
export function tocOf(md) {
  const out = []; let fence = false;
  for (const line of md.split("\n")) {
    if (line.trim().startsWith("```")) { fence = !fence; continue; }
    const m = !fence && line.match(/^(#{1,3})[ \t]+(.+?)\s*#*\s*$/);
    if (m) out.push({ level: m[1].length, text: m[2].replace(/[*`]/g, "") });
  }
  return out;
}
